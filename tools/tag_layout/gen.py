"""Generate crates/halo_map/src/layout.rs from OpenCE's C headers.

    python tools/tag_layout/gen.py [--opence ../OpenCE] [--clang clang]

Compiles probe.c with the flags OpenCE's Windows build gives game units
(i686-pc-windows-msvc, MSVC layout) to LLVM IR, reads each `layout__*`
constant, and writes them as Rust constants grouped by struct.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
OUTPUT = REPO / "crates" / "halo_map" / "src" / "layout.rs"


def find_clang(explicit):
    candidates = [explicit] if explicit else ["clang", r"C:\Program Files\LLVM\bin\clang.exe"]
    for candidate in candidates:
        if candidate and (shutil.which(candidate) or Path(candidate).is_file()):
            return candidate
    sys.exit("clang not found; pass --clang")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--opence", type=Path, default=REPO.parent / "OpenCE")
    parser.add_argument("--clang")
    args = parser.parse_args()
    opence = args.opence.resolve()
    clang = find_clang(args.clang)

    port = json.loads((opence / "port/linux/port.json").read_text(encoding="utf-8"))
    game = port["game"]

    with tempfile.TemporaryDirectory() as tmp:
        tags_header = Path(tmp) / "halo_msvc_tags.h"
        # MSVC gives struct tags first named in a prototype file scope; clang
        # needs them declared up front (as OpenCE's own build does)
        subprocess.run([sys.executable, "tools/linux_msvc_semantics.py", "--output", str(tags_header),
                        "--tags", "source"], cwd=opence, check=True)
        command = [
            clang, "--target=i686-pc-windows-msvc", "-fms-extensions", "-fcommon", "-std=gnu89", "-w",
            "-D_USE_32BIT_TIME_T",
            *[f"-D{d}" for d in game.get("defines", [])],
            "-include", "port/windows/include/halo_windows_prefix.h",
            "-include", str(tags_header),
            "-Iport/windows/include/crt", "-Iport/windows/include",
            "-iquote", "port/linux/include", "-iquote", "port/linux/game",
            *[f"-I{d}" for d in game.get("include_dirs", [])],
            "-Iport/include/xdk",
            "-S", "-emit-llvm", "-o", "-", str(HERE / "probe.c"),
        ]
        result = subprocess.run(command, cwd=opence, capture_output=True, text=True)
        if result.returncode != 0:
            sys.exit(result.stderr)

    values = defaultdict(dict)
    for match in re.finditer(r"^@layout__(\w+?)__(\w+) = .*? i32 (-?\d+)", result.stdout, re.M):
        struct, field, value = match.groups()
        values[struct][field] = int(value)
    if not values:
        sys.exit("no layout constants found in clang output")

    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=opence,
                            capture_output=True, text=True).stdout.strip() or "unknown"
    lines = [
        "//! Struct layouts of the Xbox cache file's tags (byte offsets and sizes).",
        "//!",
        f"//! GENERATED by `tools/tag_layout/gen.py` from OpenCE ({commit}); do not edit.",
        "//! Measured by clang from the game's own C definitions (i686 MSVC ABI).",
        "",
        "#![allow(dead_code)]",
    ]
    for struct in sorted(values):
        lines += ["", f"pub mod {struct} {{"]
        fields = values[struct]
        for field in sorted(fields, key=lambda f: (f != "SIZEOF", fields[f], f)):
            lines.append(f"    pub const {field.upper()}: usize = {fields[field]:#x};")
        lines.append("}")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(REPO)}: {sum(len(v) for v in values.values())} constants")


if __name__ == "__main__":
    main()
